class PageParser(HTMLParser):
    BLOCKS = {
        "p", "li", "h1", "h2", "h3", "h4", "h5", "h6",
        "div", "br", "tr", "td", "section", "article"
    }
    SKIP = {"script", "style", "noscript"}

    # Temporary marker inserted for decimal <ol><li> numbering that exists
    # visually in the browser but is not returned by HTMLParser.handle_data().
    DECIMAL_LI_MARKER = "[[DECIMAL-LI:{}]]"

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self.links = []
        self._href = None
        self._anchor_text = []
        self._skip_depth = 0

        # Stack of ordered lists. Each entry keeps its own counter and whether
        # its visual marker is decimal. We only synthesize decimal markers;
        # Arabic/English alpha sub-items already appear in the source text.
        self._ol_stack = []

    @staticmethod
    def _ordered_list_is_decimal(attrs, depth: int) -> bool:
        attrs_dict = {str(k).lower(): (v or "") for k, v in attrs}
        list_type = attrs_dict.get("type", "").strip()
        style = attrs_dict.get("style", "").lower()
        css_class = attrs_dict.get("class", "").lower()

        alpha_or_roman_tokens = (
            "lower-alpha", "upper-alpha", "lower-latin", "upper-latin",
            "lower-roman", "upper-roman",
        )

        if list_type in {"a", "A", "i", "I"}:
            return False

        if any(token in style or token in css_class for token in alpha_or_roman_tokens):
            return False

        if list_type == "1" or "decimal" in style or "decimal" in css_class:
            return True

        # Browser default for a top-level <ol> is decimal.
        # For nested default <ol>, be conservative so we do not invent numbers
        # for a sub-list whose CSS may be alphabetic.
        return depth == 0

    def handle_starttag(self, tag, attrs):
        tag = tag.lower()

        if tag in self.SKIP:
            self._skip_depth += 1
            return

        if self._skip_depth:
            return

        if tag == "ol":
            attrs_dict = {str(k).lower(): (v or "") for k, v in attrs}
            try:
                start_value = int(attrs_dict.get("start") or 1)
            except ValueError:
                start_value = 1

            self._ol_stack.append({
                "next": start_value,
                "decimal": self._ordered_list_is_decimal(
                    attrs,
                    depth=len(self._ol_stack),
                ),
            })
            self.parts.append("\n")
            return

        if tag in self.BLOCKS:
            self.parts.append("\n")

        if tag == "li" and self._ol_stack:
            current = self._ol_stack[-1]
            if current["decimal"]:
                number = current["next"]
                current["next"] += 1

                # Put the marker on its own line so it cannot break Article
                # heading detection if an unrelated ordered list contains links.
                self.parts.append(
                    self.DECIMAL_LI_MARKER.format(number) + "\n"
                )

        if tag == "a":
            self._href = dict(attrs).get("href")
            self._anchor_text = []

    def handle_endtag(self, tag):
        tag = tag.lower()

        if tag in self.SKIP:
            if self._skip_depth:
                self._skip_depth -= 1
            return

        if self._skip_depth:
            return

        if tag == "ol":
            if self._ol_stack:
                self._ol_stack.pop()
            self.parts.append("\n")
            return

        if tag in self.BLOCKS:
            self.parts.append("\n")

        if tag == "a" and self._href:
            anchor_text = clean_display_text("".join(self._anchor_text))
            self.links.append((anchor_text, self._href))
            self._href = None
            self._anchor_text = []

    def handle_data(self, data):
        if self._skip_depth:
            return

        self.parts.append(data)

        if self._href is not None:
            self._anchor_text.append(data)


def fetch(url: str) -> str:
    headers = {
        "User-Agent": "AIEP-PDPL-Capstone/5.0 (educational project)"
    }

    response = requests.get(url, headers=headers, timeout=45)
    response.raise_for_status()
    response.encoding = response.apparent_encoding or "utf-8"
    return response.text


def parse_page(html: str, base_url: str):
    parser = PageParser()
    parser.feed(html)

    raw_text = "".join(parser.parts)
    raw_text = clean_matching_text(raw_text)

    # Keep line boundaries for diagnostics while removing excessive blank lines.
    lines = [line.strip() for line in raw_text.splitlines()]
    text = "\n".join(line for line in lines if line)

    links = [
        (anchor_text, urljoin(base_url, href))
        for anchor_text, href in parser.links
    ]

    return text, links


def find_english_url(links):
    for anchor_text, href in links:
        if anchor_text.strip().lower() == "en":
            return href
    return None


