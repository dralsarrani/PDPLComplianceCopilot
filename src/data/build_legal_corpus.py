def validate_articles(articles, expected):
    numbers = [row["article_number"] for row in articles]
    expected_numbers = list(range(1, expected + 1))

    count_ok = len(articles) == expected
    sequence_ok = numbers == expected_numbers
    nonempty_ok = all(bool(row["official_text"].strip()) for row in articles)

    return {
        "count_ok": count_ok,
        "sequence_ok": sequence_ok,
        "nonempty_ok": nonempty_ok,
        "status": "PASS" if count_ok and sequence_ok and nonempty_ok else "REVIEW",
    }


# Expected top-level paragraph counts for the regulations.
# These are structural checks only: they verify that visible 1., 2., 3. ...
# markers were not lost during HTML extraction.
#
# IMPORTANT: SDAIA's published Arabic and English versions are not always
# formatted with the same marker style.  For example:
# - IR Article 21/23: Arabic uses decimal markers, English uses lettered bullets.
# - TR Article 3: Arabic publishes three numbered paragraphs followed by an
#   unnumbered final sentence, while English publishes that sentence as item 4.
# We therefore validate each language against its OWN official structure rather
# than forcing AR and EN to have identical numbering.
IR_MAIN_PARAGRAPH_COUNTS_AR = {
    1: 9, 2: 3, 3: 3, 4: 7, 5: 2, 6: 3, 7: 3, 8: 3, 9: 2,
    10: 5, 11: 2, 12: 5, 13: 3, 15: 3, 16: 4, 17: 5, 18: 2,
    19: 2, 20: 6, 21: 5, 22: 5, 23: 2, 24: 5, 25: 4, 26: 6,
    27: 2, 28: 3, 29: 3, 30: 4, 32: 4, 33: 6, 36: 3, 37: 6,
}

IR_MAIN_PARAGRAPH_COUNTS_EN = {
    1: 9, 2: 3, 3: 3, 4: 7, 5: 2, 6: 3, 7: 3, 8: 3, 9: 2,
    10: 5, 11: 2, 12: 5, 13: 3, 15: 3, 16: 4, 17: 5, 18: 2,
    19: 2, 20: 6, 22: 5, 24: 5, 25: 4, 26: 6, 27: 2, 28: 3,
    29: 3, 30: 4, 32: 4, 33: 6, 36: 3, 37: 6,
}

# Track B uses the current 9-article transfer regulation. Articles 5, 8 and 9
# are single unnumbered provisions in both languages.
TR_MAIN_PARAGRAPH_COUNTS_AR = {
    1: 5, 2: 3, 3: 3, 4: 2, 6: 2, 7: 2,
}

TR_MAIN_PARAGRAPH_COUNTS_EN = {
    1: 5, 2: 3, 3: 4, 4: 2, 6: 2, 7: 2,
}

MAIN_PARAGRAPH_COUNTS = {
    ("IR", "ar"): IR_MAIN_PARAGRAPH_COUNTS_AR,
    ("IR", "en"): IR_MAIN_PARAGRAPH_COUNTS_EN,
    ("TR", "ar"): TR_MAIN_PARAGRAPH_COUNTS_AR,
    ("TR", "en"): TR_MAIN_PARAGRAPH_COUNTS_EN,
}

VISIBLE_DECIMAL_RE = re.compile(r"(?:^|\s)(\d{1,2})\.\s")


def validate_paragraph_numbering(articles, code: str, language: str):
    """
    Validate structural top-level numbering for IR/TR.

    PDPL numbering is already present as literal legal text (for example 1- ...),
    so this validator intentionally does not alter or gate PDPL.
    """
    expected_map = MAIN_PARAGRAPH_COUNTS.get((code, language))

    if not expected_map:
        return {
            "status": "PASS",
            "issues": "",
        }

    by_number = {
        row["article_number"]: row["official_text"]
        for row in articles
    }

    issues = []

    for article_number, expected_count in expected_map.items():
        text = by_number.get(article_number, "")
        found = [
            int(value)
            for value in VISIBLE_DECIMAL_RE.findall(text)
        ]

        expected_sequence = list(range(1, expected_count + 1))

        # Keep only the first expected_count markers for the top-level sequence.
        # Cross-references use parentheses, e.g. "(1)", and therefore are not
        # matched by VISIBLE_DECIMAL_RE.
        if found[:expected_count] != expected_sequence:
            issues.append(
                f"A{article_number:02d}: expected {expected_sequence}, "
                f"found {found[:expected_count]}"
            )

    return {
        "status": "PASS" if not issues else "REVIEW",
        "issues": " | ".join(issues),
    }


# ---------------------------------------------------------------------
# Main build
# ---------------------------------------------------------------------
def main():
    # Remove stale "final" outputs from earlier runs.
    # They will be recreated only if ALL validation checks pass.
    for stale_name in ("legal_articles_full.csv", "legal_articles_full.json"):
        stale_path = OUT / stale_name
        if stale_path.exists():
            stale_path.unlink()

    corpus = []
    report = []

    for code, meta in DOCS.items():
        print(f"\nProcessing {code}...")

        # ---------------- Arabic ----------------
        html_ar = fetch(meta["url_ar"])
        text_ar, links = parse_page(html_ar, meta["url_ar"])

        ar_articles, ar_missing = split_articles(
            text=text_ar,
            code=code,
            language="ar",
            expected=meta["expected"],
        )

        ar_validation = validate_articles(ar_articles, meta["expected"])
        ar_numbering = validate_paragraph_numbering(ar_articles, code, "ar")

        for article in ar_articles:
            official_text = clean_display_text(article["official_text"])

            corpus.append({
                "record_id": f"{code}-A{article['article_number']:02d}-AR",
                "document_code": code,
                "document_name": meta["name_ar"],
                "article_number": article["article_number"],
                "article_title": article["article_title"],
                "language": "ar",
                "official_text": official_text,
                "normalized_text": normalize_arabic(official_text),
                "source_entity": SOURCE_ENTITY_AR,
                "source_url": meta["url_ar"],
                "verification_source": meta["verification_source_ar"],
                "verification_url": meta["verification_url"],
            })

        # ---------------- English ----------------
        english_url = find_english_url(links)
        en_articles = []
        en_missing = []

        if english_url:
            html_en = fetch(english_url)
            text_en, _ = parse_page(html_en, english_url)

            en_articles, en_missing = split_articles(
                text=text_en,
                code=code,
                language="en",
                expected=meta["expected"],
            )

        en_validation = validate_articles(en_articles, meta["expected"])
        en_numbering = validate_paragraph_numbering(en_articles, code, "en")

        for article in en_articles:
            official_text = clean_display_text(article["official_text"])

            corpus.append({
                "record_id": f"{code}-A{article['article_number']:02d}-EN",
                "document_code": code,
                "document_name": meta["name_en"],
                "article_number": article["article_number"],
                "article_title": article["article_title"],
                "language": "en",
                "official_text": official_text,
                "normalized_text": official_text,
                "source_entity": SOURCE_ENTITY_EN,
                "source_url": english_url or "",
                "verification_source": meta["verification_source_en"],
                "verification_url": meta["verification_url"],
            })

        report.append({
            "document_code": code,
            "expected_per_language": meta["expected"],
            "arabic_extracted": len(ar_articles),
            "english_extracted": len(en_articles),
            "arabic_missing_articles": ",".join(map(str, ar_missing)),
            "english_missing_articles": ",".join(map(str, en_missing)),
            "arabic_status": ar_validation["status"],
            "english_status": en_validation["status"],
            "arabic_numbering_status": ar_numbering["status"],
            "english_numbering_status": en_numbering["status"],
            "arabic_numbering_issues": ar_numbering["issues"],
            "english_numbering_issues": en_numbering["issues"],
            "english_url_detected": english_url or "",
        })

    # -----------------------------------------------------------------
    # Always save the extraction report.
    # -----------------------------------------------------------------
    report_path = OUT / "extraction_report.csv"

    with open(report_path, "w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(report[0].keys()))
        writer.writeheader()
        writer.writerows(report)

    expected_total = sum(meta["expected"] * 2 for meta in DOCS.values())
    all_pass = all(
        row["arabic_status"] == "PASS"
        and row["english_status"] == "PASS"
        and row["arabic_numbering_status"] == "PASS"
        and row["english_numbering_status"] == "PASS"
        for row in report
    )

    record_ids = [row["record_id"] for row in corpus]
    unique_ids_ok = len(record_ids) == len(set(record_ids))
    total_ok = len(corpus) == expected_total

    print("\nExtraction report:")
    for row in report:
        print(row)

    print(f"\nExpected total records: {expected_total}")
    print(f"Extracted records:      {len(corpus)}")
    print(f"Unique record IDs:      {'PASS' if unique_ids_ok else 'REVIEW'}")

    # -----------------------------------------------------------------
    # Safety gate: never label bad extraction as final.
    # -----------------------------------------------------------------
    if not (all_pass and total_ok and unique_ids_ok):
        debug_csv = OUT / "legal_articles_debug.csv"
        debug_json = OUT / "legal_articles_debug.json"

        if corpus:
            fields = list(corpus[0].keys())

            with open(debug_csv, "w", encoding="utf-8-sig", newline="") as file:
                writer = csv.DictWriter(file, fieldnames=fields)
                writer.writeheader()
                writer.writerows(corpus)

            debug_json.write_text(
                json.dumps(corpus, ensure_ascii=False, indent=2),
                encoding="utf-8",
            )

        raise SystemExit(
            "\nVALIDATION FAILED — final corpus was NOT written.\n"
            "Open data/processed/extraction_report.csv and review the failing rows.\n"
            "Debug extraction was saved as legal_articles_debug.csv/json."
        )

    # -----------------------------------------------------------------
    # Final outputs are written ONLY after all checks pass.
    # Remove any debug files left from a previous failed run.
    # -----------------------------------------------------------------
    for debug_name in ("legal_articles_debug.csv", "legal_articles_debug.json"):
        debug_path = OUT / debug_name
        if debug_path.exists():
            debug_path.unlink()

    fields = list(corpus[0].keys())

    csv_path = OUT / "legal_articles_full.csv"
    with open(csv_path, "w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=fields)
        writer.writeheader()
        writer.writerows(corpus)

    json_path = OUT / "legal_articles_full.json"
    json_path.write_text(
        json.dumps(corpus, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print("\nSUCCESS — validated legal corpus created.")
    print(f"CSV : {csv_path}")
    print(f"JSON: {json_path}")
    print(f"TOTAL: {len(corpus)} records")


if __name__ == "__main__":
    main()
