def arabic_heading_pattern(article_number: int) -> re.Pattern:
    phrase = AR_ORDINALS[article_number]
    words = re.split(r"\s+", phrase.strip())

    # Allows the website HTML to split one heading across multiple text nodes/lines.
    phrase_pattern = r"[\s\u00a0]+".join(re.escape(word) for word in words)

    return re.compile(
        r"المادة[\s\u00a0]+"
        + phrase_pattern
        + r"\s*[:：]",
        flags=re.UNICODE,
    )


EN_ANY_HEADING = re.compile(
    r"(?im)^Article[ \t\u00a0]+(\d+)(?:[ \t]*[:：][^\n]*)?[ \t]*$"
)


def find_arabic_sequence(text: str, expected: int):
    """
    Find articles 1..expected in legal order using explicit Arabic ordinal phrases.
    This works even if headings appear inline with the previous article.
    """
    selected = []
    cursor = 0
    missing = []

    for number in range(1, expected + 1):
        pattern = arabic_heading_pattern(number)
        match = pattern.search(text, cursor)

        if not match:
            missing.append(number)
            continue

        selected.append((number, match))
        cursor = match.end()

    return selected, missing


def find_english_sequence(text: str, expected: int):
    """
    Select heading lines Article 1 ... Article N.

    Handles both official formats used by SDAIA:
      PDPL:  "Article 1"
      IR/TR: "Article 1: Definitions"

    Matching is restricted to a whole heading line so a cross-reference such as
    "under Article 12" inside legal text is not mistaken for a new article.
    """
    selected = []
    cursor = 0
    missing = []

    for number in range(1, expected + 1):
        pattern = re.compile(
            rf"(?im)^Article[ \t\u00a0]+{number}"
            rf"(?:[ \t]*[:：][^\n]*)?[ \t]*$"
        )
        match = pattern.search(text, cursor)

        if not match:
            missing.append(number)
            continue

        selected.append((number, match))
        cursor = match.end()

    return selected, missing


def next_any_heading_start(text: str, language: str, after: int):
    """
    Find a following heading belonging to another legal document.
    Used to stop the final expected article before appended related content.
    """
    tail = text[after:]

    if language == "en":
        match = EN_ANY_HEADING.search(tail)
        return after + match.start() if match else None

    # Generic Arabic legal heading with a colon.
    match = re.search(
        r"المادة[\s\u00a0]+[\u0600-\u06FF\s]+?\s*[:：]",
        tail,
        flags=re.UNICODE,
    )
    return after + match.start() if match else None


FOOTER_MARKERS = (
    "chevron_left",
    "جميع الحقوق محفوظة",
    "All rights reserved",
    "\nملخص\n",
    "\nOverview\n",

    # On some SDAIA knowledge-center pages, the next legal document title is
    # appended immediately after the final article. Treat those titles as
    # hard stop markers so they are not absorbed into the previous article.
    "Regulation on Personal Data Transfer outside the Kingdom",
    "The Implementing Regulation of the Personal Data Protection Law",
    "لائحة نقل البيانات الشخصية إلى خارج المملكة",
    "اللائحة التنفيذية لنظام حماية البيانات الشخصية",
)


def footer_start(text: str, after: int):
    candidates = []

    for marker in FOOTER_MARKERS:
        pos = text.find(marker, after)
        if pos != -1:
            candidates.append(pos)

    return min(candidates) if candidates else len(text)


DECIMAL_LI_RE = re.compile(r"\[\[DECIMAL-LI:(\d+)\]\]")


def restore_ordered_list_numbers(text: str) -> str:
    """
    Convert temporary HTML ordered-list markers into visible paragraph numbers.

    Example:
        [[DECIMAL-LI:1]] text  ->  1. text

    This matters because browsers render <ol><li> numbers visually, while
    HTMLParser.handle_data() receives only the list item text.
    """
    text = DECIMAL_LI_RE.sub(lambda m: f"{m.group(1)}. ", text)

    # Defensive cleanup in case future non-decimal markers are introduced.
    text = re.sub(r"\[\[[A-Z0-9_-]+:[^\]]+\]\]", " ", text)

    return text


def strip_known_title_prefix(text: str, title: str) -> str:
    """
    Regulation titles may appear after the colon as part of the extracted segment.
    Remove exactly one known title prefix from official_text.
    """
    text = clean_display_text(text)

    if not title:
        return text

    title_clean = clean_display_text(title)

    if text.casefold().startswith(title_clean.casefold()):
        return text[len(title_clean):].lstrip(" -–—:：")

    return text


def split_articles(
    text: str,
    code: str,
    language: str,
    expected: int,
):
    if language == "ar":
        selected, missing = find_arabic_sequence(text, expected)
    else:
        selected, missing = find_english_sequence(text, expected)

    articles = []

    if missing:
        return articles, missing

    for index, (number, match) in enumerate(selected):
        body_start = match.end()

        if index + 1 < len(selected):
            body_end = selected[index + 1][1].start()
        else:
            # For the final expected article, stop before another document or footer.
            possible_ends = [footer_start(text, body_start)]

            next_heading = next_any_heading_start(text, language, body_start)
            if next_heading is not None:
                possible_ends.append(next_heading)

            body_end = min(possible_ends)

        title = TITLES[(code, language)].get(number, "")
        raw_body = text[body_start:body_end]
        raw_body = restore_ordered_list_numbers(raw_body)
        body = strip_known_title_prefix(raw_body, title)

        articles.append({
            "article_number": number,
            "article_title": title,
            "official_text": body,
        })

    return articles, missing


