WS = re.compile(r"\s+")
AR_DIACRITICS = re.compile(r"[\u0617-\u061A\u064B-\u0652\u0670\u06D6-\u06ED]")


def clean_matching_text(text: str) -> str:
    """Remove invisible direction marks that can break heading matching."""
    return (
        text.replace("\ufeff", "")
        .replace("\u200e", "")
        .replace("\u200f", "")
        .replace("\u202a", "")
        .replace("\u202b", "")
        .replace("\u202c", "")
    )


def clean_display_text(text: str) -> str:
    text = clean_matching_text(text)
    return WS.sub(" ", text).strip()


def normalize_arabic(text: str) -> str:
    """
    Search-only Arabic normalisation.
    official_text remains untouched except normal whitespace cleanup.
    """
    text = unicodedata.normalize("NFKC", text)
    text = AR_DIACRITICS.sub("", text)
    text = text.replace("ـ", "")

    for char in "أإآٱ":
        text = text.replace(char, "ا")

    text = text.replace("ى", "ي")
    text = text.replace("ة", "ه")

    return WS.sub(" ", text).strip()


